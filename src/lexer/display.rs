//! User-friendly token display for diagnostics.

use super::literal::{
    parse_byte_char_literal, parse_byte_string_literal, parse_char_literal,
    parse_float_literal, parse_int_literal, parse_string_literal,
};
use super::token::Token;
use std::borrow::Cow;

impl<'src> Token<'src> {
    #[inline]
    pub fn to_user_string(&self) -> Cow<'_, str> {
        match self {
            Token::Ident(s) => Cow::Owned(format!("`{}`", s.as_str())),
            // Literal arms re-parse the raw slice.  This is a cold path —
            // only rendered when a diagnostic points at the token — so
            // the re-parse cost is bounded by diagnostics, not lexing,
            // and the rendered strings are byte-identical to the eager
            // design (including every error message).
            Token::IntLiteral(s) => match parse_int_literal(s, 10, "integer literal overflow") {
                Ok(n) => Cow::Owned(format!("the number `{}`", n)),
                Err(e) => Cow::Owned(format!("invalid integer literal: {}", e)),
            },
            Token::FloatLiteral(s) => match parse_float_literal(s) {
                Ok(n) => Cow::Owned(format!("the number `{}`", n)),
                Err(e) => Cow::Owned(format!("invalid float literal: {}", e)),
            },
            Token::StringLiteral(s) => match parse_string_literal(s) {
                Ok(v) => Cow::Owned(format!("the string `\"{}\"`", v)),
                Err(e) => Cow::Owned(format!("invalid string literal: {}", e)),
            },
            Token::CharLiteral(s) => match parse_char_literal(s) {
                Ok(c) => Cow::Owned(format!(
                    "the character `'{}'`",
                    char::from_u32(c).unwrap_or('\u{FFFD}')
                )),
                Err(e) => Cow::Owned(format!("invalid character literal: {}", e)),
            },
            Token::ByteCharLiteral(s) => match parse_byte_char_literal(s) {
                Ok(b) => Cow::Owned(format!("the byte character `b'{}'`", char::from(b))),
                Err(e) => Cow::Owned(format!("invalid byte character literal: {}", e)),
            },
            Token::ByteStringLiteral(s) => match parse_byte_string_literal(s) {
                Ok(b) => Cow::Owned(format!("byte string `{:?}`", b)),
                Err(e) => Cow::Owned(format!("invalid byte string literal: {}", e)),
            },
            Token::Def => "`def`".into(),
            Token::Set => "`set`".into(),
            Token::Return => "`return`".into(),
            Token::If => "`if`".into(),
            Token::Else => "`else`".into(),
            Token::For => "`for`".into(),
            Token::While => "`while`".into(),
            Token::Loop => "`loop`".into(),
            Token::Let => "`let`".into(),
            Token::Type => "`type`".into(),
            Token::Trait => "`trait`".into(),
            Token::Impl => "`impl`".into(),
            Token::Import => "`import`".into(),
            Token::Extern => "`extern`".into(),
            Token::True => "`true`".into(),
            Token::False => "`false`".into(),
            Token::Match => "`match`".into(),
            Token::And => "`and`".into(),
            Token::Or => "`or`".into(),
            Token::Not => "`not`".into(),
            Token::Mut => "`mut`".into(),
            Token::Ref => "`ref`".into(),
            Token::Ro => "`ro`".into(),
            Token::Move => "`move`".into(),
            Token::Dyn => "`dyn`".into(),
            Token::As => "`as`".into(),
            Token::Catch => "`catch`".into(),
            Token::Panic => "`panic`".into(),
            Token::Unsafe => "`unsafe`".into(),
            Token::Async => "`async`".into(),
            Token::Await => "`await`".into(),
            Token::Comptime => "`comptime`".into(),
            Token::Leave => "`leave`".into(),
            Token::Continue => "`continue`".into(),
            Token::Where => "`where`".into(),
            Token::Requires => "`requires`".into(),
            Token::Ensures => "`ensures`".into(),
            Token::Invariant => "`invariant`".into(),
            Token::Constraint => "`constraint`".into(),
            Token::Generate => "`generate`".into(),
            Token::Isolate => "`isolate`".into(),
            Token::SelfKw => "`Self`".into(),
            Token::Plus => "`+`".into(),
            Token::Minus => "`-`".into(),
            Token::Star => "`*`".into(),
            Token::Slash => "`/`".into(),
            Token::Percent => "`%`".into(),
            Token::Ampersand => "`&`".into(),
            Token::Pipe => "`|`".into(),
            Token::Caret => "`^`".into(),
            Token::Tilde => "`~`".into(),
            Token::Bang => "`!`".into(),
            Token::Question => "`?`".into(),
            Token::Dot => "`.`".into(),
            Token::DotDot => "`..`".into(),
            Token::DotDotEq => "`..=`".into(),
            Token::Comma => "`,`".into(),
            Token::Semicolon => "`;`".into(),
            Token::Colon => "`:`".into(),
            Token::ColonColon => "`::`".into(),
            Token::Assign => "`=`".into(),
            Token::Arrow => "`->`".into(),
            Token::FatArrow => "`=>`".into(),
            Token::LParen => "`(`".into(),
            Token::RParen => "`)`".into(),
            Token::LBrace => "`{`".into(),
            Token::RBrace => "`}`".into(),
            Token::LBracket => "`[`".into(),
            Token::RBracket => "`]`".into(),
            Token::Lt => "`<`".into(),
            Token::Gt => "`>`".into(),
            Token::EqEq => "`==`".into(),
            Token::Neq => "`!=`".into(),
            Token::Le => "`<=`".into(),
            Token::Ge => "`>=`".into(),
            Token::PlusEq => "`+=`".into(),
            Token::MinusEq => "`-=`".into(),
            Token::StarEq => "`*=`".into(),
            Token::SlashEq => "`/=`".into(),
            Token::ShlEq => "`<<=`".into(),
            Token::ShrEq => "`>>=`".into(),
            Token::Shl => "`<<`".into(),
            Token::Shr => "`>>`".into(),
            Token::At => "`@`".into(),
            Token::Default => "`default`".into(),
            Token::Copy => "`copy`".into(),
            Token::By => "`by`".into(),
            Token::In => "`in`".into(),
            Token::Auto => "`auto`".into(),
            Token::With => "`with`".into(),
            Token::When => "`when`".into(),
            Token::Const => "`const`".into(),
            Token::Codomain => "`codomain`".into(),
            Token::Finally => "`finally`".into(),
            Token::Pub => "`pub`".into(),
            Token::Pure => "`pure`".into(),
            Token::Io => "`io`".into(),
            Token::Linear => "`linear`".into(),
            Token::Consume => "`consume`".into(),
            Token::Wrap => "`wrap`".into(),
            Token::Saturate => "`saturate`".into(),
            Token::Trap => "`trap`".into(),
            Token::Ieee => "`ieee`".into(),
            Token::Old => "`old`".into(),
            Token::Ghost => "`ghost`".into(),
            Token::ScopeCleanup => "`scope_cleanup`".into(),
            Token::Trigger => "`trigger`".into(),
            Token::Validate => "`validate`".into(),
            Token::Layout => "`layout`".into(),
            Token::Alignof => "`alignof`".into(),
            Token::Sizeof => "`sizeof`".into(),
            Token::Poly => "`poly`".into(),
            Token::Unbox => "`unbox`".into(),
            Token::Ellipsis => "`...`".into(),
            Token::Apostrophe => "`'`".into(),
            Token::PlusSaturate => "`+?`".into(),
            Token::PlusTrap => "`+!`".into(),
            Token::PlusWrap => "`+%`".into(),
            Token::MinusSaturate => "`-?`".into(),
            Token::MinusTrap => "`-!`".into(),
            Token::MinusWrap => "`-%`".into(),
            Token::StarSaturate => "`*?`".into(),
            Token::StarTrap => "`*!`".into(),
            Token::StarWrap => "`*%`".into(),
            Token::IntSuffix(_) => "integer with suffix".into(),
            Token::BinIntSuffix(_) => "binary integer with suffix".into(),
            Token::HexIntSuffix(_) => "hex integer with suffix".into(),
            Token::UIntSuffix(_) => "unsigned integer with suffix".into(),
            Token::BinUIntSuffix(_) => "binary unsigned integer with suffix".into(),
            Token::HexUIntSuffix(_) => "hex unsigned integer with suffix".into(),
            Token::BinLiteral(s) => match parse_int_literal(&s[2..], 2, "binary literal overflow") {
                Ok(n) => Cow::Owned(format!("the number `{}`", n)),
                Err(e) => Cow::Owned(format!("invalid binary literal: {}", e)),
            },
            Token::HexLiteral(s) => match parse_int_literal(&s[2..], 16, "hex literal overflow") {
                Ok(n) => Cow::Owned(format!("the number `{}`", n)),
                Err(e) => Cow::Owned(format!("invalid hex literal: {}", e)),
            },
            Token::Deprecated => "`deprecated`".into(),
            Token::Experimental => "`experimental`".into(),
            Token::Endian => "`endian`".into(),
            Token::BitOrder => "`bit_order`".into(),
            Token::Align => "`align`".into(),
            Token::Pad => "`pad`".into(),
            Token::Packed => "`packed`".into(),
            Token::Decreases => "`decreases`".into(),
            Token::Diverges => "`diverges`".into(),
            Token::Terminates => "`terminates`".into(),
            Token::Exhaustive => "`exhaustive`".into(),
            Token::NoAllocError => "`no_alloc_error`".into(),
            Token::NoPanic => "`no_panic`".into(),
            Token::DebugInfo => "`debug_info`".into(),
            Token::IeeeContracts => "`ieee_contracts`".into(),
            Token::AuditLog => "`audit_log`".into(),
            Token::Interrupt => "`interrupt`".into(),
            Token::MustUse => "`must_use`".into(),
            Token::MustHandle => "`must_handle`".into(),
            Token::MissingMatch => "`missing_match`".into(),
            Token::ApplyLemma => "`apply_lemma`".into(),
            Token::LinkProof => "`link_proof`".into(),
            Token::Propagates => "`propagates`".into(),
            Token::Overrides => "`overrides`".into(),
            Token::Cfg => "`cfg`".into(),
            Token::Hint => "`hint`".into(),
            Token::Exists => "`exists`".into(),
            Token::Forall => "`forall`".into(),
            Token::Implies => "`implies`".into(),
            Token::Task => "`task`".into(),
            Token::Channel => "`channel`".into(),
            Token::NoDefault => "`no_default`".into(),
            Token::Edition => "`edition`".into(),
            Token::WhitespaceOrComment => "whitespace or comment".into(),
            // Never emitted (skipped at file start / lex error elsewhere);
            // arm exists because the Token match must be exhaustive.
            Token::Bom => "byte order mark (U+FEFF)".into(),
            Token::DocComment(s) => Cow::Owned(format!("documentation comment `///{}`", s)),
            Token::ModuleDocComment(s) => {
                Cow::Owned(format!("module documentation comment `//!{}`", s))
            }
            Token::Trusted => "`trusted`".into(),
        }
    }
}
