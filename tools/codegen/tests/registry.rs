//! Registry validation tests: the real repo must be clean, and each
//! invalid shape must be reported as a hard error or a lint.

mod common;

use common::{Fixture, repo_root};
use ponent_codegen::{collect, write_generated};

#[test]
fn real_repo_collects_clean() {
    let outcome = collect(&repo_root());
    assert!(outcome.errors.is_empty(), "errors: {:#?}", outcome.errors);
    assert!(outcome.lints.is_empty(), "lints: {:#?}", outcome.lints);

    assert_eq!(outcome.coverage.len(), 3, "expected en, ru, zh");
    for row in &outcome.coverage {
        assert_eq!(
            (row.present, row.total),
            (19, 19),
            "locale {} incomplete",
            row.locale
        );
    }

    assert_eq!(
        outcome.generated.matches("include_str!").count(),
        89,
        "one embedded explain per code"
    );
    assert!(
        outcome.generated.starts_with(
            "// @generated by build.rs from error_codes/codes.toml + error_codes/*.md"
        )
    );
    assert!(outcome.generated.ends_with("];\n"));
}

#[test]
fn write_generated_is_idempotent() {
    let outcome = collect(&repo_root());
    assert!(!outcome.generated.is_empty());

    let dir = tempfile::tempdir().expect("tempdir");
    let dest = dir.path().join("error_codes_gen.rs");
    assert!(write_generated(&dest, &outcome.generated).expect("first write"));
    assert!(!write_generated(&dest, &outcome.generated).expect("second write"));
    assert!(write_generated(&dest, "different\n").expect("changed write"));

    // Empty generated (invalid registry) must never truncate the file.
    assert!(!write_generated(&dest, "").expect("empty write"));
    assert_eq!(
        std::fs::read_to_string(&dest).expect("read back"),
        "different\n"
    );
}

#[test]
fn duplicate_titles_are_a_lint_not_an_error() {
    let f = Fixture::new();
    f.base();
    f.write(
        "error_codes/codes.toml",
        "schema = 1\n\n\
         [codes.E001]\ntitle = \"Same\"\ncategory = \"parse\"\nexplain = \"E001.md\"\n\n\
         [codes.W001]\ntitle = \"Same\"\ncategory = \"type\"\nexplain = \"E002.md\"\n",
    );
    f.write(
        "error_codes/E002.md",
        "This is the E002 explanation body.\n",
    );

    let outcome = collect(f.root());
    assert!(outcome.errors.is_empty(), "errors: {:#?}", outcome.errors);
    assert_eq!(outcome.lints.len(), 1, "lints: {:#?}", outcome.lints);
    assert!(
        outcome.lints[0].contains("duplicate title \"Same\" used by both E001 and W001"),
        "unexpected lint: {}",
        outcome.lints[0]
    );
}

